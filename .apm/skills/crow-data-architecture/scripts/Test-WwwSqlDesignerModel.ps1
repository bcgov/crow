<#
.SYNOPSIS
  Validates a WWW SQL Designer portable-v1 XML model.

.DESCRIPTION
  Mirrors the bcgov/wwwsqldesigner browser import rules for portable-v1
  models and adds Crow checks that prevent silent loss when the model is
  saved, versioned, or exported. With -RequireGovernanceMetadata, every table
  must have a description and records schedule, and every column must have a
  description and a B.C. information security classification.

  A records-schedule value, when present, must be a plain-text description
  readable without a code lookup: '<records class title>: <retention period
  and the event that starts it> (ARCS|ORCS <number>)'.

  Exit code 0 means no errors. Warnings never change the exit code.
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory)]
    [string]$Path,

    [switch]$RequireGovernanceMetadata
)

$ErrorActionPreference = 'Stop'

$script:errors = [System.Collections.Generic.List[string]]::new()
$script:warnings = [System.Collections.Generic.List[string]]::new()

function Add-ModelError([string]$Message) { $script:errors.Add($Message) }
function Add-ModelWarning([string]$Message) { $script:warnings.Add($Message) }
function Exit-Validation([string]$Message, [int]$Code) {
    [Console]::Error.WriteLine("ERROR: $Message")
    exit $Code
}

$maxBytes = 1MB
$portableFormat = 'portable-v1'
$defaultSchema = 'dbo'
$portableTokens = @(
    'integer', 'decimal', 'float', 'string', 'text', 'boolean', 'date', 'time',
    'datetime', 'datetime-with-time-zone', 'binary', 'uuid', 'json', 'xml')
$classifications = @('Public', 'Protected A', 'Protected B', 'Protected C')
$keyTypes = @('PRIMARY', 'UNIQUE', 'INDEX', 'FULLTEXT')
$legendAttributes = @('name', 'title', 'author', 'application', 'created', 'modified')
# Attributes the designer reads; anything else is discarded on save.
$elementAttributes = @{
    sql                = @('format')
    datatypes          = @('db')
    table              = @('name', 'schema', 'x', 'y')
    row                = @('name', 'null', 'autoincrement')
    key                = @('type', 'name')
    relation           = @('table', 'row', 'schema', 'name')
    comment            = @()
    'records-schedule' = @()
    datatype           = @()
    default            = @()
    classification     = @()
    part               = @()
}
$maxDecimalPrecision = 1000
$maxLength = [int]::MaxValue
$trailerMarker = '@bcgov{'
$allowedParents = @{
    datatypes          = @('sql')
    legend             = @('sql')
    table              = @('sql')
    row                = @('table')
    key                = @('table')
    comment            = @('table', 'row')
    'records-schedule' = @('table')
    datatype           = @('row')
    default            = @('row')
    relation           = @('row')
    classification     = @('row')
    part               = @('key')
}
$singletons = @{
    sql   = @('datatypes', 'legend')
    table = @('comment', 'records-schedule')
    row   = @('datatype', 'default', 'comment', 'classification')
}
# The embedded datatypes registry is regenerated by the designer on load.
$registryElements = @('group', 'type')
$controlCharacters = '[\p{Cc}\u2028\u2029]'

function Get-EffectiveSchema([System.Xml.XmlElement]$Element) {
    $value = $Element.GetAttribute('schema').Trim()
    if ($value) { return $value }
    return $defaultSchema
}

function Get-TableIdentity([string]$Schema, [string]$Name) {
    return $Schema.ToLowerInvariant() + [char]0 + $Name.Trim().ToLowerInvariant()
}

function Get-ChildElement([System.Xml.XmlNode]$Node, [string]$Name) {
    return @($Node.ChildNodes | Where-Object {
            $_.NodeType -eq [System.Xml.XmlNodeType]::Element -and $_.LocalName -eq $Name
        })
}

function Test-SingleTextNode([System.Xml.XmlElement]$Element) {
    return $Element.ChildNodes.Count -eq 1 -and
        $Element.FirstChild.NodeType -in @([System.Xml.XmlNodeType]::Text, [System.Xml.XmlNodeType]::CDATA)
}

function Test-PositiveFacet([string]$Value, [long]$Maximum) {
    $number = 0L
    return [long]::TryParse($Value, [ref]$number) -and $number -ge 1 -and $number -le $Maximum
}

$scheduleFormat = '<records class title>: <retention period and the event that starts it> (ARCS|ORCS <number>)'
$schedulePattern = '^(?<title>[^:]*\p{L}[^:]*):\s*(?<retention>\S.*?)\s*\((?<reference>(?:ARCS|ORCS)\b[^()]*\d[^()]*)\)\s*$'
$schedulePeriodPattern = '(?i)\b(?:\d+|one|two|three|four|five|six|seven|eight|nine|ten|eleven|twelve|fifteen|twenty|twenty-five|thirty|forty|fifty|seventy-five|hundred)\s+(?:(?:calendar|fiscal)\s+)?(?:years?|months?|weeks?|days?)\b'
$scheduleOpenEndedPattern = '(?i)\b(?:permanently|indefinitely)\b'
$scheduleTriggerPattern = '(?i)\b(?:after|following|from|until|once|when|while)\b'
# Uppercase disposition (DE, FR, SR, OD, NA) and trigger (CY, FY, SO) codes need a lookup to read.
$scheduleCodePattern = '\b(?:DE|FR|SR|OD|NA|CY|FY|SO|ARCS|ORCS)\b'

function Get-RecordsScheduleProblem([string]$Value) {
    $match = [regex]::Match($Value, $schedulePattern)
    if (-not $match.Success) {
        return "must read as '$scheduleFormat', with the ARCS or ORCS number only in the closing brackets"
    }
    $text = $match.Groups['title'].Value + ': ' + $match.Groups['retention'].Value
    if ($text -cmatch $scheduleCodePattern) {
        return "must spell out '$($Matches[0])' in words outside the closing brackets so no code lookup is needed"
    }
    $retention = $match.Groups['retention'].Value
    $openEnded = $retention -match $scheduleOpenEndedPattern
    if (-not $openEnded -and $retention -notmatch $schedulePeriodPattern -and $retention -notmatch '(?i)\buntil\b') {
        return "must state the retention period in words, for example 'retain 7 years after the permit closes'"
    }
    if (-not $openEnded -and $retention -notmatch $scheduleTriggerPattern) {
        return "must state the event that starts the retention period, for example 'after the permit closes'"
    }
    return $null
}

function ConvertFrom-TrailerValue([string]$Value) {
    $options = [System.Text.RegularExpressions.RegexOptions]::IgnoreCase
    $Value = [regex]::Replace($Value, '%3B', ';', $options)
    $Value = [regex]::Replace($Value, '%3D', '=', $options)
    $Value = [regex]::Replace($Value, '%7B', '{', $options)
    $Value = [regex]::Replace($Value, '%7D', '}', $options)
    $Value = [regex]::Replace($Value, '%25', '%', $options)
    return $Value
}

function Get-ColumnScheduleTrailer([string]$Comment) {
    if (-not $Comment.Contains($trailerMarker)) { return $null }
    $match = [regex]::Match(
        $Comment,
        '(?s)^(?<description>.*?)\s*@bcgov\{RecordsSchedule=(?<schedule>[^{}]*)\}\s*$')
    if (-not $match.Success) {
        return [pscustomobject]@{
            Problem = 'must contain only one terminal @bcgov{RecordsSchedule=...} trailer'
            Schedule = $null
        }
    }
    if (-not $match.Groups['description'].Value.Trim()) {
        return [pscustomobject]@{
            Problem = 'requires a human-readable column description before the RecordsSchedule trailer'
            Schedule = $null
        }
    }
    return [pscustomobject]@{
        Problem = $null
        Schedule = ConvertFrom-TrailerValue $match.Groups['schedule'].Value
    }
}

function Get-RowLocation([System.Xml.XmlElement]$Row) {
    $table = $Row.ParentNode
    return '[{0}].[{1}].[{2}]' -f (Get-EffectiveSchema $table), $table.GetAttribute('name'), $Row.GetAttribute('name')
}

function Test-Datatype([System.Xml.XmlElement]$Row, [string]$Location) {
    $datatypes = @(Get-ChildElement $Row 'datatype')
    if ($datatypes.Count -eq 0) {
        Add-ModelError "${Location}: datatype is required."
        return $null
    }
    $value = $datatypes[0].InnerText.Trim()
    $match = [regex]::Match($value, '^(?<kind>[^()]+?)(?:\((?<facets>.*)\))?$')
    if (-not $match.Success) {
        Add-ModelError "${Location}: datatype '$value' is not a portable-v1 type."
        return $null
    }
    $kind = $match.Groups['kind'].Value.Trim()
    $facets = $match.Groups['facets'].Value.Trim()
    if ($portableTokens -cnotcontains $kind) {
        Add-ModelError "${Location}: datatype '$value' is not a lowercase portable-v1 token ($($portableTokens -join ', '))."
        return $null
    }
    if (-not $facets) { return $kind }
    switch ($kind) {
        'decimal' {
            $decimal = [regex]::Match($facets, '^(?<p>\d+)\s*,\s*(?<s>\d+)$')
            if (-not $decimal.Success) {
                Add-ModelError "${Location}: decimal facets '$facets' must be 'precision,scale'."
            }
            elseif (-not (Test-PositiveFacet $decimal.Groups['p'].Value $maxDecimalPrecision) -or
                $decimal.Groups['s'].Value.TrimStart('0').Length -gt 4 -or
                [long]$decimal.Groups['s'].Value -gt [long]$decimal.Groups['p'].Value) {
                Add-ModelError "${Location}: decimal facets '$facets' require 1 <= precision <= $maxDecimalPrecision and scale <= precision."
            }
        }
        { $_ -in @('string', 'binary') } {
            if ($facets -cne 'max' -and -not (Test-PositiveFacet $facets $maxLength)) {
                Add-ModelError "${Location}: $kind length '$facets' must be a positive integer or 'max'."
            }
        }
        default {
            Add-ModelError "${Location}: datatype '$kind' does not accept facets ('$facets')."
        }
    }
    return $kind
}

if (-not (Test-Path -LiteralPath $Path -PathType Leaf)) {
    Exit-Validation "Model file not found: $Path" 2
}

$bytes = [System.IO.File]::ReadAllBytes((Resolve-Path -LiteralPath $Path).ProviderPath)
if ($bytes.Length -gt $maxBytes) {
    Add-ModelError "Model is $($bytes.Length) bytes; the designer rejects saved models over $maxBytes bytes."
}
try {
    $text = [System.Text.UTF8Encoding]::new($false, $true).GetString($bytes)
}
catch {
    Exit-Validation "Model is not valid UTF-8: $($_.Exception.Message)" 1
}
if ($text.Length -gt 0 -and $text[0] -eq [char]0xFEFF) {
    Add-ModelWarning 'Model starts with a UTF-8 byte-order mark; omit it for consistent round trips.'
    $text = $text.Substring(1)
}
if ($text -match '<\s*!\s*(?:DOCTYPE|ENTITY)\b') {
    Exit-Validation 'DTD and entity declarations are not allowed.' 1
}

$settings = [System.Xml.XmlReaderSettings]::new()
$settings.DtdProcessing = [System.Xml.DtdProcessing]::Prohibit
$settings.XmlResolver = $null
$document = [System.Xml.XmlDocument]::new()
$document.XmlResolver = $null
$reader = $null
try {
    $reader = [System.Xml.XmlReader]::Create([System.IO.StringReader]::new($text), $settings)
    $document.Load($reader)
}
catch {
    Exit-Validation "Invalid XML: $($_.Exception.Message)" 1
}
finally {
    if ($reader) { $reader.Dispose() }
}

$root = $document.DocumentElement
if ($root.LocalName -cne 'sql' -or $root.NamespaceURI) {
    Add-ModelError "Root element must be un-namespaced 'sql', found '$($root.Name)'."
}
if ($root.GetAttribute('format') -cne $portableFormat) {
    Add-ModelError "Root element must declare format=""$portableFormat""."
}

foreach ($element in @($root) + @($root.SelectNodes('//*'))) {
    if ($element -eq $root) { continue }
    $name = $element.LocalName
    $parent = $element.ParentNode.LocalName
    if ($element.NamespaceURI) {
        Add-ModelError "Namespaced element '$($element.Name)' is not part of portable-v1."
        continue
    }
    if ($registryElements -ccontains $name -and $null -ne $element.SelectSingleNode('ancestor::datatypes')) {
        continue
    }
    if (-not $allowedParents.ContainsKey($name)) {
        Add-ModelError "Unknown element '$name' under '$parent' would be discarded by the designer."
        continue
    }
    if (@($allowedParents.Keys) -cnotcontains $name) {
        Add-ModelError "Element '$name' must be lowercase."
        continue
    }
    if ($allowedParents[$name] -cnotcontains $parent) {
        Add-ModelError "Misplaced element '$name' under '$parent'."
    }
    foreach ($attribute in $element.Attributes) {
        if ($name -ne 'legend' -and $elementAttributes[$name] -cnotcontains $attribute.Name) {
            Add-ModelError "Unknown attribute '$($attribute.Name)' on '$name' would be discarded by the designer."
        }
    }
    if ($name -eq 'records-schedule' -and $element.InnerText.Contains($trailerMarker)) {
        Add-ModelError "A records-schedule under '$parent' contains the reserved metadata marker '$trailerMarker'."
    }
    elseif ($name -eq 'comment' -and $element.InnerText.Contains($trailerMarker)) {
        if ($parent -cne 'row') {
            Add-ModelError "A comment under '$parent' contains the reserved metadata marker '$trailerMarker'."
        }
        else {
            $columnSchedule = Get-ColumnScheduleTrailer $element.InnerText
            if ($columnSchedule.Problem) {
                Add-ModelError "Column comment under '$parent' $($columnSchedule.Problem)."
            }
            elseif (-not $columnSchedule.Schedule) {
                Add-ModelError "Column comment under '$parent' has an empty RecordsSchedule trailer value."
            }
            else {
                $problem = Get-RecordsScheduleProblem $columnSchedule.Schedule
                if ($problem) { Add-ModelError "Column comment under '$parent' RecordsSchedule $problem." }
            }
        }
    }
}
foreach ($attribute in $root.Attributes) {
    if ($elementAttributes['sql'] -cnotcontains $attribute.Name -and $attribute.Prefix -cne 'xmlns' -and $attribute.Name -cne 'xmlns') {
        Add-ModelError "Unknown attribute '$($attribute.Name)' on 'sql' would be discarded by the designer."
    }
}
foreach ($entry in $singletons.GetEnumerator()) {
    $owners = if ($entry.Key -eq 'sql') { @($root) } else { @($root.SelectNodes("//$($entry.Key)")) }
    foreach ($owner in $owners) {
        foreach ($child in $entry.Value) {
            if (@(Get-ChildElement $owner $child).Count -gt 1) {
                Add-ModelError "Duplicate '$child' under '$($owner.LocalName)' '$($owner.GetAttribute('name'))'."
            }
        }
    }
}

$datatypesNode = Get-ChildElement $root 'datatypes' | Select-Object -First 1
if ($datatypesNode -and $datatypesNode.GetAttribute('db') -cne 'portable') {
    Add-ModelError "datatypes registry must declare db=""portable""."
}
$legend = Get-ChildElement $root 'legend' | Select-Object -First 1
if ($legend) {
    foreach ($attribute in $legend.Attributes) {
        if ($legendAttributes -cnotcontains $attribute.Name) {
            Add-ModelWarning "Legend attribute '$($attribute.Name)' is not preserved by the designer."
        }
    }
}

$tables = @(Get-ChildElement $root 'table')
if ($tables.Count -eq 0) { Add-ModelError 'Model contains no tables.' }

$identities = @{}
$tableRows = @{}
foreach ($table in $tables) {
    $tableName = $table.GetAttribute('name')
    $schema = Get-EffectiveSchema $table
    $tableLocation = "[$schema].[$tableName]"
    if (-not $tableName.Trim()) {
        Add-ModelError 'Table name cannot be empty.'
        continue
    }
    if ("$tableName$schema" -match $controlCharacters) {
        Add-ModelError "Table or schema name '$($tableLocation -replace $controlCharacters, '?')' contains control characters."
        continue
    }
    if (-not $table.HasAttribute('schema')) {
        Add-ModelWarning "${tableLocation}: schema attribute is missing; the designer assumes '$defaultSchema'."
    }
    foreach ($coordinate in @('x', 'y')) {
        if ($table.HasAttribute($coordinate) -and $table.GetAttribute($coordinate) -notmatch '^-?\d+$') {
            Add-ModelWarning "${tableLocation}: $coordinate coordinate is not an integer and becomes 0."
        }
    }
    $identity = Get-TableIdentity $schema $tableName
    if ($identities.ContainsKey($identity)) {
        Add-ModelError "Duplicate table identity ${tableLocation} (comparison is trimmed and case-insensitive)."
        continue
    }
    $identities[$identity] = $table

    $rows = [System.Collections.Generic.Dictionary[string, System.Xml.XmlElement]]::new([System.StringComparer]::Ordinal)
    $folded = @{}
    foreach ($row in Get-ChildElement $table 'row') {
        $rowName = $row.GetAttribute('name')
        if (-not $rowName) {
            Add-ModelError "${tableLocation}: row name cannot be empty."
            continue
        }
        if ($rowName -match '[&<]') {
            Add-ModelError "${tableLocation}: row name '$rowName' contains '&' or '<', which the designer does not escape when saving XML."
            continue
        }
        if ($rowName -match $controlCharacters) {
            Add-ModelError "${tableLocation}: row name '$($rowName -replace $controlCharacters, '?')' contains control characters."
            continue
        }
        if ($rows.ContainsKey($rowName)) {
            Add-ModelError "${tableLocation}: duplicate row name '$rowName'."
            continue
        }
        if ($folded.ContainsKey($rowName)) {
            Add-ModelWarning "${tableLocation}: rows '$($folded[$rowName])' and '$rowName' differ only by case and collide in case-insensitive databases."
        }
        $folded[$rowName] = $rowName
        $rows[$rowName] = $row
    }
    if ($rows.Count -eq 0) { Add-ModelError "${tableLocation}: table has no rows." }
    $tableRows[$table] = $rows

    $primaryKeys = 0
    foreach ($key in Get-ChildElement $table 'key') {
        $keyType = $key.GetAttribute('type')
        if ($key.GetAttribute('name') -match $controlCharacters) {
            Add-ModelError "${tableLocation}: key name contains control characters."
        }
        if ($keyTypes -cnotcontains $keyType) {
            Add-ModelError "${tableLocation}: key type '$keyType' must be one of $($keyTypes -join ', ')."
        }
        if ($keyType -ceq 'PRIMARY') { $primaryKeys++ }
        $parts = @(Get-ChildElement $key 'part')
        if ($parts.Count -eq 0) { Add-ModelError "${tableLocation}: key '$($key.GetAttribute('name'))' has no parts." }
        $seen = [System.Collections.Generic.HashSet[string]]::new([System.StringComparer]::Ordinal)
        foreach ($part in $parts) {
            if (-not (Test-SingleTextNode $part)) {
                Add-ModelError "${tableLocation}: key part must contain exactly one text node."
                continue
            }
            $partName = $part.InnerText
            if (-not $seen.Add($partName)) { Add-ModelError "${tableLocation}: duplicate key part '$partName'." }
            if (-not $rows.ContainsKey($partName)) { Add-ModelError "${tableLocation}: key part row '$partName' not found." }
        }
    }
    if ($primaryKeys -gt 1) { Add-ModelError "${tableLocation}: more than one PRIMARY key." }
    if ($primaryKeys -eq 0) { Add-ModelWarning "${tableLocation}: no PRIMARY key." }

    foreach ($child in @(Get-ChildElement $table 'comment') + @(Get-ChildElement $table 'records-schedule')) {
        if ($child.ChildNodes.Count -and -not (Test-SingleTextNode $child)) {
            Add-ModelError "${tableLocation}: $($child.LocalName) must contain exactly one text node."
        }
        elseif ($child.LocalName -eq 'records-schedule' -and $child.InnerText.Trim()) {
            $problem = Get-RecordsScheduleProblem $child.InnerText.Trim()
            if ($problem) { Add-ModelError "${tableLocation}: records-schedule $problem." }
        }
    }
    if ($RequireGovernanceMetadata) {
        foreach ($required in @('comment', 'records-schedule')) {
            $node = Get-ChildElement $table $required | Select-Object -First 1
            if (-not $node -or -not $node.InnerText.Trim()) {
                Add-ModelError "${tableLocation}: governance metadata requires a non-empty $required."
            }
        }
    }
}

$keyed = @{}
foreach ($table in $tables) {
    if (-not $tableRows.ContainsKey($table)) { continue }
    foreach ($row in $tableRows[$table].Values) {
        $location = Get-RowLocation $row
        foreach ($flag in @('null', 'autoincrement')) {
            if (-not $row.HasAttribute($flag)) {
                Add-ModelWarning "${location}: $flag attribute is missing; the designer treats it as '0'."
            }
            elseif (@('0', '1') -cnotcontains $row.GetAttribute($flag)) {
                Add-ModelError "${location}: $flag must be '0' or '1'."
            }
        }
        $kind = Test-Datatype $row $location
        if ($row.GetAttribute('autoincrement') -eq '1' -and $kind -and $kind -ne 'integer') {
            Add-ModelError "${location}: autoincrement requires the integer type."
        }
        foreach ($child in @(Get-ChildElement $row 'default') + @(Get-ChildElement $row 'comment')) {
            if ($child.ChildNodes.Count -and -not (Test-SingleTextNode $child)) {
                Add-ModelError "${location}: $($child.LocalName) must contain exactly one text node."
            }
        }
        $classification = Get-ChildElement $row 'classification' | Select-Object -First 1
        if ($classification) {
            if (-not (Test-SingleTextNode $classification) -or $classifications -cnotcontains $classification.InnerText) {
                Add-ModelError "${location}: classification must be exactly one of $($classifications -join ', ')."
            }
        }
        if ($RequireGovernanceMetadata) {
            $comment = Get-ChildElement $row 'comment' | Select-Object -First 1
            if (-not $comment -or -not $comment.InnerText.Trim()) {
                Add-ModelError "${location}: governance metadata requires a non-empty comment."
            }
            if (-not $classification) {
                Add-ModelError "${location}: governance metadata requires a classification."
            }
        }

        $relations = @(Get-ChildElement $row 'relation')
        if ($relations.Count -gt 1) {
            Add-ModelWarning "${location}: has $($relations.Count) relations; the designer server canonical model keeps only the first."
        }
        foreach ($relation in $relations) {
            $targetSchema = Get-EffectiveSchema $relation
            $targetTableName = $relation.GetAttribute('table')
            $targetRowName = $relation.GetAttribute('row')
            $target = $identities[(Get-TableIdentity $targetSchema $targetTableName)]
            if (-not $target) {
                Add-ModelError "${location}: relation target table [$targetSchema].[$targetTableName] not found."
                continue
            }
            $targetRows = $tableRows[$target]
            if (-not $targetRows.ContainsKey($targetRowName)) {
                Add-ModelError "${location}: relation target row [$targetSchema].[$targetTableName].[$targetRowName] not found."
                continue
            }
            $targetRow = $targetRows[$targetRowName]
            if (-not $keyed.ContainsKey($target)) {
                $keyed[$target] = @(Get-ChildElement $target 'key' | Where-Object {
                        $_.GetAttribute('type') -in @('PRIMARY', 'UNIQUE') -and
                        @(Get-ChildElement $_ 'part').Count -eq 1
                    } | ForEach-Object { @(Get-ChildElement $_ 'part')[0].InnerText })
            }
            if ($keyed[$target] -cnotcontains $targetRowName) {
                Add-ModelWarning "${location}: relation target [$targetSchema].[$targetTableName].[$targetRowName] is not a single-column PRIMARY or UNIQUE key."
            }
            $targetKind = (Get-ChildElement $targetRow 'datatype' | Select-Object -First 1).InnerText
            $sourceKind = (Get-ChildElement $row 'datatype' | Select-Object -First 1).InnerText
            if ($targetKind -and $sourceKind -and $targetKind.Trim() -cne $sourceKind.Trim()) {
                Add-ModelWarning "${location}: datatype '$sourceKind' differs from relation target datatype '$targetKind'."
            }
        }
    }
}

foreach ($warning in $script:warnings) { [Console]::Error.WriteLine("WARNING: $warning") }
if ($script:errors.Count -gt 0) {
    foreach ($message in $script:errors) { Write-Host "ERROR: $message" }
    Write-Host "Model validation failed: $($script:errors.Count) error(s), $($script:warnings.Count) warning(s)."
    exit 1
}
Write-Host "Model validation passed: $($tables.Count) table(s), $($script:warnings.Count) warning(s)."
exit 0
